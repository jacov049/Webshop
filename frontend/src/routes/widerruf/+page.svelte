<h1>Widerrufsbelehrung</h1>

<div class="stack">
	<p class="muted">
		Platzhalter-Muster nach Art. 246a § 1 Abs. 2 EGBGB. Vor Live-Betrieb rechtlich prüfen und in
		<code>docs/widerruf.md</code> final abstimmen (insbesondere Fristbeginn, Ausnahmen bei
		versiegelten/digitalen Waren, Wertersatz).
	</p>

	<section class="card">
		<h2>Widerrufsrecht</h2>
		<p>
			Du hast das Recht, binnen vierzehn Tagen ohne Angabe von Gründen diesen Vertrag zu
			widerrufen. Die Widerrufsfrist beträgt vierzehn Tage ab dem Tag, an dem du oder ein von
			dir benannter Dritter, der nicht der Beförderer ist, die Waren in Besitz genommen
			hast/haben.
		</p>
		<p>
			Um dein Widerrufsrecht auszuüben, musst du uns über das
			<a href="/kontakt">Kontaktformular</a> unter Angabe deiner Bestellnummer mittels einer
			eindeutigen Erklärung über deinen Entschluss, diesen Vertrag zu widerrufen, informieren.
		</p>
	</section>

	<section class="card">
		<h2>Folgen des Widerrufs</h2>
		<p>
			Im Falle eines wirksamen Widerrufs erstatten wir dir den gezahlten Betrag in der
			ursprünglich verwendeten Kryptowährung. Aufgrund der Kursvolatilität von Bitcoin und
			Monero erfolgt die Erstattung [in Höhe des ursprünglichen EUR-Gegenwerts / in Höhe des
			ursprünglich gezahlten Krypto-Betrags — vor Live-Betrieb verbindlich festlegen und mit
			der Zahlungsabwicklung/Buchhaltung abstimmen].
		</p>
	</section>

